/**
 * Render worker. A separate process (Node, or the Bun runtime inside the desktop app) so a render
 * never blocks the caller: bundles the Timeline composition with esbuild, computes its size and
 * length, and drives @neon/motion's headless renderer (Chrome over CDP + FFmpeg). Emits NDJSON
 * events on stdout.
 *
 *   node packages/render/src/worker.ts --job /tmp/job.json
 */
import { existsSync, statSync } from 'node:fs';
import { homedir } from 'node:os';
import { mkdir, readFile } from 'node:fs/promises';
import { delimiter, dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { bundleComposition, bundleNodeModule, fingerprint, motionVersion, nodeModulesAbove, renderMedia, renderStill, type CompositionMetadata, type FfmpegBinaries } from '@neon/motion/node';
import { projectDurationFrames } from '@neon/core';
import { neonHome } from '@neon/core/node';
import type { RenderJobSpec, WorkerEvent } from './types.ts';

type Job<K extends RenderJobSpec['kind']> = Extract<RenderJobSpec, { kind: K }>;
type Size = { width: number; height: number };
type MetadataFn = (args: { props: Record<string, unknown> }) => CompositionMetadata;

const TIMELINE_COMPOSITION_ID = 'Timeline';
const SHEET_COMPOSITION_ID = 'ContactSheet';
/** Bumped when the generated entry or bundle layout changes, to invalidate cached bundles. */
const BUNDLE_FORMAT = 'neon-motion-2';

type WorkerEventBody = { [K in WorkerEvent['type']]: Omit<Extract<WorkerEvent, { type: K }>, 'neon'> }[WorkerEvent['type']];

function emit(event: WorkerEventBody): void {
  process.stdout.write(`${JSON.stringify({ neon: 1, ...event })}\n`);
}

function log(line: string): void {
  process.stderr.write(`${line}\n`);
}

/** Source directory of @neon/motion (its code is part of every bundle). */
function motionSourceDir(): string | null {
  try {
    return dirname(fileURLToPath(import.meta.resolve('@neon/motion')));
  } catch {
    return null;
  }
}

/**
 * The bundle entry: registers each installed pack's components with the workspace, then hands
 * the Timeline and ContactSheet compositions to the render page (picked by composition id).
 */
export function generateEntry(spec: Pick<RenderJobSpec, 'entryPoint' | 'packs'>): string {
  const packs = spec.packs ?? [];
  return [
    '// generated by @neon/render — do not edit',
    "import { registerRenderRoot } from '@neon/motion/render-page';",
    `import { TimelineComposition, ContactSheet, registerRuntimeComponents } from ${JSON.stringify(spec.entryPoint)};`,
    ...packs.map((p, i) => `import * as pack${i} from ${JSON.stringify(p.entry)};`),
    ...packs.map((p, i) => `registerRuntimeComponents(${JSON.stringify(p.name)}, pack${i} as unknown as Record<string, unknown>);`),
    `registerRenderRoot({ ${JSON.stringify(TIMELINE_COMPOSITION_ID)}: TimelineComposition, ${JSON.stringify(SHEET_COMPOSITION_ID)}: ContactSheet });`,
    '',
  ].join('\n');
}

interface PreparedBundle {
  dir: string;
  metadata: Record<typeof TIMELINE_COMPOSITION_ID | typeof SHEET_COMPOSITION_ID, MetadataFn>;
}

async function ensureBundle(spec: RenderJobSpec): Promise<PreparedBundle> {
  const packs = spec.packs ?? [];
  const motionDir = motionSourceDir();
  const key = await fingerprint(
    [...spec.watchDirs, ...(motionDir ? [motionDir] : [])],
    `${BUNDLE_FORMAT}|${motionVersion()}|${spec.entryPoint}|${packs.map((p) => `${p.name}@${p.entry}`).join(',')}`,
  );
  const resolveDir = dirname(spec.entryPoint);
  // Pack sources can live outside the workspace (~/.neon-video/packs); resolve their bare imports
  // (react, @neon/motion, @neon/fx-kit…) from the workspace so there is exactly one copy of each.
  const nodePaths = nodeModulesAbove(resolveDir);
  const cachedDir = join(spec.bundleCacheDir, key);
  const cached = existsSync(join(cachedDir, 'index.html'));
  if (!cached) {
    emit({ type: 'stage', stage: 'bundling', message: `Bundling compositions${packs.length ? ` + ${packs.length} FX pack${packs.length === 1 ? '' : 's'}` : ''}` });
  }
  await mkdir(spec.bundleCacheDir, { recursive: true });
  const bundle = await bundleComposition({
    entry: { source: generateEntry(spec), resolveDir, sourcefile: 'neon-render-entry.tsx' },
    outDir: spec.bundleCacheDir,
    cacheKey: key,
    nodePaths,
    title: 'Neon render',
  });
  // The metadata function lives in .tsx sources Node can't import directly; bundle it for Node too.
  const metadataFile = join(bundle.dir, 'node', 'metadata.mjs');
  if (!existsSync(metadataFile)) {
    await bundleNodeModule({
      entry: { source: `export { calculateTimelineMetadata, calculateSheetMetadata } from ${JSON.stringify(spec.entryPoint)};`, resolveDir, sourcefile: 'neon-metadata-entry.ts' },
      outFile: metadataFile,
      nodePaths,
    });
  }
  emit({ type: 'bundle', cached: bundle.cached, location: bundle.dir });
  const mod = (await import(pathToFileURL(metadataFile).href)) as { calculateTimelineMetadata?: MetadataFn; calculateSheetMetadata?: MetadataFn };
  if (typeof mod.calculateTimelineMetadata !== 'function') throw new Error(`${spec.entryPoint} does not export calculateTimelineMetadata`);
  if (typeof mod.calculateSheetMetadata !== 'function') throw new Error(`${spec.entryPoint} does not export calculateSheetMetadata`);
  return { dir: bundle.dir, metadata: { [TIMELINE_COMPOSITION_ID]: mod.calculateTimelineMetadata, [SHEET_COMPOSITION_ID]: mod.calculateSheetMetadata } };
}

/**
 * ffmpeg/ffprobe for the renderer: $NEON_FFMPEG_PATH / $NEON_FFPROBE_PATH, then PATH, then the usual
 * install locations, then the copies the app installs into <NEON_HOME>/tools. Packaged apps start
 * with a minimal PATH, so PATH alone would miss Homebrew's and the app's own ffmpeg.
 */
export function resolveBinaries(env: NodeJS.ProcessEnv = process.env): FfmpegBinaries {
  const win = process.platform === 'win32';
  const dirs = [
    ...(env['PATH'] ?? '').split(delimiter),
    ...(win ? [join(homedir(), 'AppData', 'Local', 'Microsoft', 'WinGet', 'Links')] : ['/opt/homebrew/bin', '/usr/local/bin', '/usr/bin', '/bin']),
    join(neonHome(), 'tools'),
  ].filter(Boolean);
  const find = (name: string): string | undefined => {
    const file = win ? `${name}.exe` : name;
    for (const dir of dirs) {
      const candidate = join(dir, file);
      try {
        if (statSync(candidate).isFile()) return candidate;
      } catch {
        /* not here */
      }
    }
    return undefined;
  };
  return {
    ffmpeg: env['NEON_FFMPEG_PATH'] || find('ffmpeg') || 'ffmpeg',
    ffprobe: env['NEON_FFPROBE_PATH'] || find('ffprobe') || 'ffprobe',
  };
}

/** Timeline frame range (project fps) → composition frame range (output fps), clamped. */
export function scaleFrameRange(range: [number, number] | null | undefined, projectFrames: number, scale: number): [number, number] | null {
  if (!range) return null;
  const total = Math.max(1, Math.round(projectFrames * scale));
  const from = Math.max(0, Math.min(total - 1, Math.round(range[0] * scale)));
  const to = Math.max(from, Math.min(total - 1, Math.round(range[1] * scale)));
  return [from, to];
}

async function renderVideo(spec: Job<'video'>, bundle: PreparedBundle, signal: AbortSignal): Promise<Size> {
  const inputProps = {
    project: spec.project,
    assetBaseUrl: spec.assetBaseUrl,
    assetQuery: spec.assetQuery ?? '',
    render: { width: spec.preset.width, height: spec.preset.height, fps: spec.preset.fps },
  };
  emit({ type: 'stage', stage: 'rendering', message: 'Resolving composition' });
  const composition = bundle.metadata[TIMELINE_COMPOSITION_ID]({ props: inputProps });
  const scale = composition.fps / spec.project.meta.fps;
  const frameRange = scaleFrameRange(spec.frameRange, projectDurationFrames(spec.project), scale);
  const totalFrames = frameRange ? frameRange[1] - frameRange[0] + 1 : composition.durationInFrames;
  emit({ type: 'start', totalFrames, width: composition.width, height: composition.height, fps: composition.fps });
  await renderMedia({
    bundleDir: bundle.dir,
    props: inputProps,
    composition: { id: TIMELINE_COMPOSITION_ID, ...composition },
    frameRange,
    outputPath: spec.outputPath,
    crf: spec.preset.crf,
    concurrency: spec.concurrency ?? null,
    browserExecutable: spec.browserExecutable ?? null,
    binaries: resolveBinaries(),
    signal,
    onLog: log,
    onProgress: ({ progress, renderedFrames, encodedFrames }) => {
      emit({ type: 'progress', progress, renderedFrames, encodedFrames });
    },
  });
  return { width: composition.width, height: composition.height };
}

/**
 * A still renders the Timeline at project size and lets Chrome rasterise it at the requested
 * width, so text and FX keep their proportions. A sheet renders the ContactSheet composition at
 * frame 0 (each cell is the timeline frozen at its frame).
 */
async function renderPng(spec: Job<'still' | 'sheet'>, bundle: PreparedBundle, signal: AbortSignal): Promise<Size> {
  const timeline = { project: spec.project, assetBaseUrl: spec.assetBaseUrl, assetQuery: spec.assetQuery ?? '', render: null };
  const shot: { id: keyof PreparedBundle['metadata']; props: Record<string, unknown>; frame: number; scale: number; cells: number } =
    spec.kind === 'still'
      ? { id: TIMELINE_COMPOSITION_ID, props: timeline as Record<string, unknown>, frame: spec.frame, scale: spec.width / spec.project.meta.width, cells: 1 }
      : { id: SHEET_COMPOSITION_ID, props: { timeline, frames: spec.frames, cols: spec.cols, width: spec.width } as Record<string, unknown>, frame: 0, scale: 1, cells: spec.frames.length };
  emit({ type: 'stage', stage: 'rendering', message: 'Resolving composition' });
  const metadata = bundle.metadata[shot.id]({ props: shot.props });
  const composition = { id: shot.id, width: metadata.width, height: metadata.height, fps: metadata.fps, durationInFrames: metadata.durationInFrames };
  emit({ type: 'start', totalFrames: shot.cells, width: composition.width, height: composition.height, fps: composition.fps });
  const result = await renderStill({
    bundleDir: bundle.dir,
    props: shot.props,
    composition,
    frame: Math.min(composition.durationInFrames - 1, Math.max(0, shot.frame)),
    outputPath: spec.outputPath,
    scale: shot.scale,
    browserExecutable: spec.browserExecutable ?? null,
    binaries: resolveBinaries(),
    signal,
    onLog: log,
  });
  emit({ type: 'progress', progress: 1, renderedFrames: shot.cells, encodedFrames: shot.cells });
  return { width: result.width, height: result.height };
}

async function main(): Promise<void> {
  const jobIndex = process.argv.indexOf('--job');
  const jobPath = jobIndex >= 0 ? process.argv[jobIndex + 1] : undefined;
  if (!jobPath) throw new Error('Usage: worker.ts --job <spec.json>');
  const spec = JSON.parse(await readFile(jobPath, 'utf8')) as RenderJobSpec;

  const started = Date.now();
  const controller = new AbortController();
  const onTerminate = () => {
    if (controller.signal.aborted) return;
    emit({ type: 'stage', stage: 'rendering', message: 'Cancelling…' });
    controller.abort(new Error('Render cancelled'));
  };
  process.on('SIGTERM', onTerminate);
  process.on('SIGINT', onTerminate);

  const bundle = await ensureBundle(spec);
  if (controller.signal.aborted) throw controller.signal.reason;

  let size: Size;
  switch (spec.kind) {
    case 'video':
      size = await renderVideo(spec, bundle, controller.signal);
      break;
    case 'still':
    case 'sheet':
      size = await renderPng(spec, bundle, controller.signal);
      break;
    default: {
      const unreachable: never = spec;
      throw new Error(`Unknown job kind ${JSON.stringify(unreachable)}`);
    }
  }
  emit({ type: 'done', outputPath: spec.outputPath, durationMs: Date.now() - started, ...size });
}

// Only run as the worker process (tests import the helpers above).
if (process.argv.includes('--job')) {
  main().then(
    () => process.exit(0),
    (err: unknown) => {
      const e = err instanceof Error ? err : new Error(String(err));
      emit({ type: 'error', message: e.message, stack: e.stack });
      process.exit(1);
    },
  );
}
